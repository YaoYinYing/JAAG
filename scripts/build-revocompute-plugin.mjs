// Builds dist/jaag-builder.revo.js: the canonical REvoCompute `jaag-builder`
// input-workspace plugin with the JAAG core bundled in. The result is a single
// file that attaches global.JAAGCore and then registers the plugin, so it works
// when REvoCompute loads it as a runner-owned workspace plugin (plain <script>).

import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const distDir = resolve(root, 'dist');

const core = readFileSync(resolve(distDir, 'jaag-core.global.js'), 'utf8');
const plugin = readFileSync(resolve(root, 'integration/revocompute/jaag-builder/index.js'), 'utf8');

const bundle = [
    '/* REvoCompute — JAAG structure input builder (standalone plugin bundle). */',
    '/* Core is Apache-2.0 (JAAG); plugin is GPL-3.0-only (REvoCompute). */',
    '/* Generated by scripts/build-revocompute-plugin.mjs. */',
    core,
    '',
    plugin,
    ''
].join('\n');

mkdirSync(distDir, { recursive: true });
writeFileSync(resolve(distDir, 'jaag-builder.revo.js'), bundle);
console.log(`wrote dist/jaag-builder.revo.js (${bundle.length} bytes)`);
